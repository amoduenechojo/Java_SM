public class DivisibleBySeven{
    public static void main(String [] args){
    
        int bank = 0;

        for(int count = 1; count <= 100; count ++){
            if(count % 7 == 0){
                bank = bank + 1;
            }
   }
        System.out.println("The amount of numbers are: " + bank);



}
    }
